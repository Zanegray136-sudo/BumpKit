// --- cabinets the person adds themselves ------------------------------------
export const CUSTOM_MAKER = "Custom";
let customList: LedPanel[] = [];
let customStamp = 0;

/** Replaces the person's own cabinets (called when a project loads or changes). */
export function setCustomPanels(list: LedPanel[]) {
  if (list === customList) return;
  customList = list;
  customStamp++;
}
export const getCustomPanels = () => customList;
/** Changes whenever the custom list does, so cached plans know to recalculate. */
export const customPanelStamp = () => customStamp;
export const findPanel = (model: string): LedPanel | undefined =>
  customList.find((p) => p.model === model) ?? ledPanels.find((p) => p.model === model);
