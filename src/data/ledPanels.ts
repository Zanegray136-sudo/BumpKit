const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });

/** Alphabetical by manufacturer, then series, then model (numbers sort naturally). */
export const ledPanels: LedPanel[] = [...rawPanels].sort(
  (a, b) =>
    collator.compare(a.manufacturer, b.manufacturer) ||
    collator.compare(a.series ?? "", b.series ?? "") ||
    collator.compare(a.model, b.model)
);

